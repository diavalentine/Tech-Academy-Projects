
//switch statement practice

function colorPick(color){
    switch(color){
        case "Red":
            document.write("You picked red!");
            break;
        case "Blue":
            document.write("You picked blue!");
            break;
        case "Yellow":
            document.write("You picked yellow!");
            break;
        case "Green":
            document.write("You picked green!");
            break;
    }
}